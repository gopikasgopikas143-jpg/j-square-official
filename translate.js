/* ── REFACTORED ROBUST TRANSLATION PARSER ENGINE ── */
function applyTranslations(lang) {
  // Query all possible text-bearing nodes safely
  var allText = document.querySelectorAll(
    'h1, h2, h3, h4, h5, p, span, a, button, label, li, div.section-label, .proj-location, .proj-title, .proj-price, .test-text, .test-name, .test-loc, .about-quote, .hero-stat-label, .svc-short, .svc-cta, .edge-text strong, .edge-text span, .why-card-text h4, .why-card-text p, .proj-detail, .footer-bottom p, .fcb-item span'
  );

  allText.forEach(function(el) {
    // Avoid targeting interactive parent container structural blocks
    if (el.children.length > 0 && !el.classList.contains('lang-dropdown-btn') && !el.innerText.includes('→')) return;
    if (el.id === "currentLangLabel") return; 

    // Extract dynamic or existing text context
    var original = el.getAttribute('data-en') || el.textContent.trim();
    if (!el.getAttribute('data-en')) {
      el.setAttribute('data-en', original);
    }

    if (lang === 'ta') {
      var key = original.replace(/\s+/g, ' ').trim(); // Normalize broken white spaces
      var entry = translations[key];
      
      // Fallback loose keyword tracking array check
      if (!entry) {
        for (var k in translations) {
          if (k.toLowerCase() === key.toLowerCase() || k.trim() === key) {
            entry = translations[k];
            break;
          }
        }
      }

      if (entry && entry.ta) {
        el.textContent = entry.ta;
      }
    } else {
      // Revert completely to original English state values
      el.textContent = el.getAttribute('data-en');
    }
  });

  // Handle Input Form Placeholders
  var inputs = document.querySelectorAll('input[placeholder], textarea[placeholder]');
  var placeholderMap = {
    'Full name': 'முழு பெயர்',
    '10-digit mobile': '10 இலக்க மொபைல்',
    'Tell us more...': 'மேலும் சொல்லுங்கள்...',
    '🔍 Search area, title, location…': '🔍 பகுதி, தலைப்பு, இடம் தேடுங்கள்…'
  };

  inputs.forEach(function(inp) {
    var orig = inp.getAttribute('data-ph-en') || inp.getAttribute('placeholder');
    if (!inp.getAttribute('data-ph-en')) inp.setAttribute('data-ph-en', orig);
    
    if (lang === 'ta' && placeholderMap[orig]) {
      inp.setAttribute('placeholder', placeholderMap[orig]);
    } else {
      inp.setAttribute('placeholder', inp.getAttribute('data-ph-en'));
    }
  });
}

// Global Logic Event Controller Channels
function applyLanguageUI(langCode) {
  var desktopLabel = document.getElementById("currentLangLabel");
  if (desktopLabel) {
    desktopLabel.textContent = langCode === "ta" ? "தமிழ்" : "English";
  }
  if (langCode === 'ta') {
    document.body.classList.add('tamil-mode');
  } else {
    document.body.classList.remove('tamil-mode');
  }
}

function autoSwitchLang(langCode) {
  currentLang = langCode;
  localStorage.setItem("preferred_lang", langCode);
  applyTranslations(langCode);
  applyLanguageUI(langCode);
}

// Lifecycle Initial Execution Thread
document.addEventListener("DOMContentLoaded", function() {
  var savedLang = localStorage.getItem("preferred_lang") || "en";
  autoSwitchLang(savedLang);
});
